#' Generate a resolvable incomplete-block baseline
#'
#' Each consecutive pair of rows is one complete replicate. The function
#' uses the caller's random-number stream; call set.seed() for reproducibility.
#' @param rows Positive even number of rows.
#' @param columns Positive number of columns.
#' @return A data frame with row, column, replicate and treatment.
#' @export
#' @examples
#' set.seed(2026)
#' layout <- generate_blocks()
#' validate_layout(layout)
generate_blocks <- function(rows = 20L, columns = 10L) {
  integer_scalar <- function(x) {
    is.numeric(x) && length(x) == 1L && is.finite(x) &&
      x > 0 && x == floor(x)
  }
  if (!integer_scalar(rows) || !integer_scalar(columns) || rows %% 2 != 0) {
    stop("rows must be a positive even integer; columns a positive integer")
  }
  layout <- expand.grid(column = seq_len(columns), row = seq_len(rows))
  layout$replicate <- (layout$row + 1L) %/% 2L
  layout$treatment <- unlist(lapply(seq_len(rows / 2L), function(i) {
    sample.int(2L * columns)
  }), use.names = FALSE)
  layout[c("row", "column", "replicate", "treatment")]
}

#' Validate a paired-row resolvable layout
#' @param layout Data frame generated by generate_blocks().
#' @return TRUE, or an error explaining an invalid layout.
#' @export
validate_layout <- function(layout) {
  required <- c("row", "column", "replicate", "treatment")
  if (!is.data.frame(layout) || !all(required %in% names(layout)) ||
      nrow(layout) == 0L) stop("layout must contain plot coordinates and assignments")
  x <- layout[required]
  valid <- vapply(x, function(z) is.numeric(z) && all(is.finite(z)) &&
                    all(z > 0 & z == floor(z)), logical(1))
  if (!all(valid)) stop("layout values must be finite positive integers")
  nr <- max(x$row); nc <- max(x$column); nt <- 2L * nc
  if (nr %% 2 != 0 || nrow(x) != nr * nc ||
      anyDuplicated(x[c("row", "column")]) ||
      any(x$replicate != (x$row + 1L) %/% 2L)) {
    stop("layout must be a complete rectangular grid with paired-row replicates")
  }
  ok <- vapply(split(x$treatment, x$replicate), function(z) {
    identical(sort(z), as.numeric(seq_len(nt))) ||
      identical(sort(z), seq_len(nt))
  }, logical(1))
  if (!all(ok)) stop("each replicate must contain every treatment exactly once")
  TRUE
}
